import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const storage=new Map();const ctx={localStorage:{getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)}};ctx.window=ctx;
const file=new URL('../data-guard.js',import.meta.url);
assert.ok(fs.existsSync(file),'proteção compartilhada de backup deve existir');
vm.runInNewContext(fs.readFileSync(file,'utf8'),ctx);
storage.set('d7_deleted_produtos','["p1"]');
ctx.D7Data.importBackup({produtos:[{id:'p1'},{id:'p2',preco:10}],deleted:{produtos:['p3']}});
ctx.D7Data.importBackup({d7_produtos:JSON.stringify([{id:'p3'},{id:'p4'}])});
assert.deepEqual(JSON.parse(JSON.stringify(ctx.D7Data.get('produtos'))).map(x=>x.id),['p2','p4']);
ctx.D7Data.set('produtos',[{id:'p1'},{id:'p4'}]);
assert.deepEqual(JSON.parse(JSON.stringify(ctx.D7Data.get('produtos'))).map(x=>x.id),['p4']);
assert.ok(ctx.D7Data.backup().deleted.produtos.includes('p1'));
assert.ok(ctx.D7Data.backup().deleted.produtos.includes('p3'));
const before=JSON.stringify([...storage]);
assert.throws(()=>ctx.D7Data.importBackup({deleted:{clientes:['c1']},produtos:'invalid json'}));
assert.equal(JSON.stringify([...storage]),before,'backup rejeitado não pode alterar dados ou exclusões permanentes');
console.log('DATA_GUARD_OK');
